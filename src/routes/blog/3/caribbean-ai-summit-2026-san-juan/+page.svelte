		<p>In July, Code Puerto Rico ran <strong>AI for Executives: What Matters Now</strong> at Aloft San Juan — a shorter afternoon for business leaders with live demos and straight talk, not vapor. That was our own session, separate from the Summit. Speakers on the flyer: me, Vincent Guarino (San Juan Export Services), and Will Rosellini (Darrow Industries).</p>

